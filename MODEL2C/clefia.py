ROUNDS128 = 18

def bytes_to_words(b: bytes) -> List[int]:
    """Convert 16-byte block to 4 x 32-bit words (big-endian)."""
    return list(struct.unpack('>4I', b))

def words_to_bytes(w: List[int]) -> bytes:
    """Convert 4 x 32-bit words to 16-byte block (big-endian)."""
    return struct.pack('>4I', *w)

def mul2(x: int) -> int:
    """GF(2^8) multiplication by 2, primitive polynomial x^8+x^4+x^3+x^2+1 (0x11d)."""
    x &= 0xff
    if x & 0x80:
        x ^= 0x0e
    return ((x << 1) & 0xff) | (x >> 7)

def mul4(x: int) -> int:
    return mul2(mul2(x))

def mul6(x: int) -> int:
    return mul2(x) ^ mul4(x)

def mul8(x: int) -> int:
    return mul2(mul4(x))

def mulA(x: int) -> int:
    return mul2(x) ^ mul8(x)

def f0(rk: int, x: int) -> int:
    """F0: S-box layer (S0,S1,S0,S1) followed by diffusion matrix M0."""
    t = rk ^ x
    t0 = S0[(t >> 24) & 0xff]
    t1 = S1[(t >> 16) & 0xff]
    t2 = S0[(t >> 8) & 0xff]
    t3 = S1[t & 0xff]
    y0 = t0 ^ mul2(t1) ^ mul4(t2) ^ mul6(t3)
    y1 = mul2(t0) ^ t1 ^ mul6(t2) ^ mul4(t3)
    y2 = mul4(t0) ^ mul6(t1) ^ t2 ^ mul2(t3)
    y3 = mul6(t0) ^ mul4(t1) ^ mul2(t2) ^ t3
    return (y0 << 24) | (y1 << 16) | (y2 << 8) | y3

def f1(rk: int, x: int) -> int:
    """F1: S-box layer (S1,S0,S1,S0) followed by diffusion matrix M1."""
    t = rk ^ x
    t0 = S1[(t >> 24) & 0xff]
    t1 = S0[(t >> 16) & 0xff]
    t2 = S1[(t >> 8) & 0xff]
    t3 = S0[t & 0xff]
    y0 = t0 ^ mul8(t1) ^ mul2(t2) ^ mulA(t3)
    y1 = mul8(t0) ^ t1 ^ mulA(t2) ^ mul2(t3)
    y2 = mul2(t0) ^ mulA(t1) ^ t2 ^ mul8(t3)
    y3 = mulA(t0) ^ mul2(t1) ^ mul8(t2) ^ t3
    return (y0 << 24) | (y1 << 16) | (y2 << 8) | y3

def sigma(x: List[int]) -> List[int]:
    """Sigma diffusion function for key schedule."""
    y = [0] * 4
    y[0] = ((x[0] & 0x01ffffff) << 7) | ((x[1] & 0xfe000000) >> 25)
    y[1] = ((x[1] & 0x01ffffff) << 7) | (x[3] & 0x0000007f)
    y[2] = (x[0] & 0xfe000000) | ((x[2] & 0xffffff80) >> 7)
    y[3] = ((x[2] & 0x0000007f) << 25) | ((x[3] & 0xffffff80) >> 7)
    return y

def gfn4(r: int, rk: List[int], x: List[int]) -> List[int]:
    """Generalized Feistel Network 4 branches (encryption direction)."""
    t = x[:]
    for i in range(r):
        t[1] ^= f0(rk[2 * i], t[0])
        t[3] ^= f1(rk[2 * i + 1], t[2])
        # Rotate left words
        temp = t[0]
        t[0] = t[1]
        t[1] = t[2]
        t[2] = t[3]
        t[3] = temp
    # Final output permutation (undo last rotation), as in gfn4 of the C reference
    y = [t[3], t[0], t[1], t[2]]
    return y

def gfn_inv4(r: int, rk: List[int], x: List[int]) -> List[int]:
    """Inverse GFN4 for decryption."""
    t = x[:]
    for i in range(r):
        t[1] ^= f0(rk[2 * (r - i) - 2], t[0])
        t[3] ^= f1(rk[2 * (r - i) - 1], t[2])
        temp0, temp1, temp2, temp3 = t[0], t[1], t[2], t[3]
        t[0] = temp3
        t[1] = temp0
        t[2] = temp1
        t[3] = temp2
    y = [t[1], t[2], t[3], t[0]]
    return y

def _key_schedule_128(key: bytes) -> Tuple[Tuple[int, ...], Tuple[int, ...]]:
    if len(key) != 16:
        raise ValueError("CLEFIA-128 requires 16-byte key")
    k = bytes_to_words(key)
    l = gfn4(12, CON128, k)
    wk = k[:]
    rk = [0] * 36
    for i in range(9):
        t = [
            l[0] ^ CON128[24 + 4 * i],
            l[1] ^ CON128[24 + 4 * i + 1],
            l[2] ^ CON128[24 + 4 * i + 2],
            l[3] ^ CON128[24 + 4 * i + 3]
        ]
        l = sigma(l)
        if i % 2 == 1:
            t[0] ^= k[0]
            t[1] ^= k[1]
            t[2] ^= k[2]
            t[3] ^= k[3]
        rk[4 * i] = t[0]
        rk[4 * i + 1] = t[1]
        rk[4 * i + 2] = t[2]
        rk[4 * i + 3] = t[3]
    return tuple(wk), tuple(rk)

# The key schedule depends only on the key, so cache it: the analysis code
# encrypts many blocks under one key.
_KS_CACHE = {}

def key_schedule_128(key: bytes) -> Tuple[List[int], List[int]]:
    """Key schedule for CLEFIA-128. Returns (whitening_keys wk[4], round_keys rk[36])."""
    key = bytes(key)
    ks = _KS_CACHE.get(key)
    if ks is None:
        if len(_KS_CACHE) > 64:
            _KS_CACHE.clear()
        ks = _KS_CACHE[key] = _key_schedule_128(key)
    return list(ks[0]), list(ks[1])

def _check_rounds(rounds: int) -> None:
    if not 1 <= rounds <= ROUNDS128:
        raise ValueError(f"rounds must be in 1..{ROUNDS128}")

def encrypt_block(plaintext: bytes, key: bytes, rounds: int = ROUNDS128) -> bytes:
    """Encrypt one 16-byte block with CLEFIA-128.

    rounds < 18 gives the reduced-round variant used in cryptanalysis:
    input whitening, the first `rounds` rounds (rk[0..2*rounds-1]), output whitening.
    """
    _check_rounds(rounds)
    wk, rk = key_schedule_128(key)
    t = bytes_to_words(plaintext)
    t[1] ^= wk[0]
    t[3] ^= wk[1]
    c = gfn4(rounds, rk, t)
    c[1] ^= wk[2]
    c[3] ^= wk[3]
    return words_to_bytes(c)

def decrypt_block(ciphertext: bytes, key: bytes, rounds: int = ROUNDS128) -> bytes:
    """Decrypt one 16-byte block with CLEFIA-128 (inverse of encrypt_block with the same rounds)."""
    _check_rounds(rounds)
    wk, rk = key_schedule_128(key)
    t = bytes_to_words(ciphertext)
    t[1] ^= wk[2]
    t[3] ^= wk[3]
    p = gfn_inv4(rounds, rk, t)
    p[1] ^= wk[0]
    p[3] ^= wk[1]
    return words_to_bytes(p)

